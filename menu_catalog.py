def expanded_menus():
    result=[]
    for category, meals, tags, ingredients, names in GROUPS:
        for name in names.split(','):
            searchable = name + ',' + ingredients
            allergens = {a for a,words in ALLERGEN_WORDS.items() if any(w in searchable for w in words)}
            # Most prepared dishes may contain wheat/soy in sauces. Conservative,
            # deliberately not a claim of an allergen-free recipe.
            allergens.update(['밀','대두'])
            result.append(dict(name=name, category=category, meal=meals.split(','),
                tags=list(dict.fromkeys(tags.split(',')+[name])), avoid=sorted(allergens),
                ingredients=ingredients.split(','), items=[], nutrition_known=False,
                base_story=f'{name}을 고를 때는 실제 재료와 조리법을 확인하고, 취향에 따라 곁들임을 선택해 보세요. 식당과 레시피에 따라 구성은 달라질 수 있습니다.',
                story_type='🍽️ 메뉴 선택 참고'))
    return result
